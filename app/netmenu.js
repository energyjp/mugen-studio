'use strict';
// THE ONLINE MENU: one Lua mod, shipped by the website build and the desktop
// export alike as external/mods/mugen-studio/net-menu.lua (vfslib generates
// it; the desktop export carries the same text). The Mods tab can switch it
// off (modmgr.js, 'net-menu'): then neither build carries it or its font.
//
// A screenpack made for MUGEN has no online menu, and one added to its title
// menu is not always seen: a menu drawn as art, one item at a time, or with its
// item text blanked shows an added NETWORK entry as nothing at all (Mortal
// Kombat II Remix). So nothing is added to the screenpack any more. Instead,
// on the title screen of every screenpack:
//
//  1. A small line, PRESS N FOR ONLINE, drawn in the engine's own 6x9 font on
//     a dark pill near the bottom of the screen, or near the top when the
//     screenpack's title menu reaches down there.
//  2. N opens a box titled NETWORK, drawn over the title background in the
//     same font, so the screenpack's menu style cannot hide it. Its items call
//     the engine's own handlers (main.t_itemname), the same call the title
//     menu makes, so a lobby behaves exactly as it does from a NETWORK menu.
//     The desktop engine has no web join, so there JOIN GAME opens a second
//     box with the saved addresses, NEW ADDRESS and BACK, as the stock menu has.
//  3. The menu the engine opens once both players of a lobby are connected
//     (main.menu.submenu.server, never shown on the title) is added at load
//     when the screenpack has none. The build adds it to the screenpack's own
//     file too (motifcompat.serverGroup); this covers a pack it did not reach.
//  4. On a screenpack with no NETWORK menu of its own, that lobby menu is
//     drawn as a box like the NETWORK one. The engine draws it in the title
//     menu's style, and a title menu drawn as art cannot show it (Capcom vs
//     SNK Evolution Rev 2 draws each item as a whole-screen picture, so the
//     lobby looked like a frozen title). Only the drawing is replaced: the
//     engine's own menu loop still reads the synced input and runs the item,
//     so both players stay in step. A pack with its own NETWORK menu was made
//     for online play and draws its lobby itself.
//
// The online-only rows are written only when online is true - a build whose
// vfslib wantOnlineName allows them - so every other copy of the text carries
// neither the rows nor their ids. Each row is shown only while its handler
// exists, checked when the box opens: some handlers come from mods that load
// after this one (alphabetical order), and main.webBuild is set by one too.
//
// The text is built from single-quoted strings, never a template literal:
// generated Lua may carry no backtick and no ${ (GRAIL), and it needs no Lua
// \n. It is ASCII; callers wrap it as Buffer.from(text, 'latin1').

// In the folder that holds every add-on of the Studio's: modmgr.js VPATHS,
// the add-ons' registry, names the same string (this file requires nothing;
// tools/test-mods-build.js checks the two agree).
const NET_MENU_VPATH = 'external/mods/mugen-studio/net-menu.lua';
const HINT_TEXT = 'PRESS N FOR ONLINE';

// THE FONT. fontNew looks in the screenpack's folder (and its font/) before
// the game's font/, so a pack that ships its own f-6x9.def replaces the
// engine's: Capcom vs SNK Evolution Rev 2 has a 14x14 italic one under that
// name, and the box text ran past its frame and the hint over the pack's
// footer. Both builds ship this copy of the engine's f-6x9.def under a name no
// pack has; its glyphs (File = f-6x9.sff) are looked for beside the def first,
// so they are the engine's font/f-6x9.sff. The mod falls back to f-6x9.def
// when the file is not there (a build made before it).
const NET_MENU_FONT_VPATH = 'font/net-menu-6x9.def';
function netMenuFontDef() {
  return [
    '; The engine\'s 6x9 font (font/f-6x9.def), under a name no screenpack ships,',
    '; for the online menu (' + NET_MENU_VPATH + '). Written by Mugen Studio.',
    '',
    '[FNT v2]',
    'fntversion = 2,00',
    'name = "6x9 variable"',
    '',
    '[Def]',
    'Type = bitmap',
    'BankType = palette',
    'Size = 5,8',
    'Spacing = 1,2',
    'Offset = 0,0',
    'File = f-6x9.sff',
    '',
  ].join('\r\n');
}

// A Lua single-quoted string of printable ASCII.
function luaStr(s) {
  const t = String(s == null ? '' : s).replace(/[^\x20-\x7e]/g, '');
  return '\'' + t.replace(/\\/g, '\\\\').replace(/'/g, '\\\'') + '\'';
}


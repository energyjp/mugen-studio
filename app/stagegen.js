'use strict';
//
// AN IMAGE BECOMES A STAGE.
//
// Drop a picture, get a playable stage: one .sff holding the picture as sprite
// 0,0 and one .def that positions it, tells the engine where the ground is,
// how far the camera may travel and where the two fighters start.
//
// This is logogen.js's shape with stage arithmetic - the SFF half is the same
// job (a single PNG wrapped in an SFFv2 container) and is deliberately written
// the same way, because that writer is field-proven against a reference file
// byte for byte. The arithmetic lives in public/ikemen/stage-geom.js, SHARED
// with the Studio's placement dialog, so the preview and the .def are computed
// by the same code and cannot disagree.
//
// WHY THIS IS SO MUCH SMALLER THAN THE OLD TOOL. Mugen Resources/stage_tool
// (2010) runs an image through ImageSplit.java, which chops it into PCX pieces,
// and then Elecbyte's sprmaker.exe to assemble an SFF v1. All of that exists to
// work around v1: PCX, a 256-color palette, and sprite size limits. We write
// SFF v2 with the PNG embedded whole, which Ikemen reads natively - so the
// jigsaw solver, the palette quantizer and sprmaker are all dead weight here.
// What was worth keeping from that tool is its WORKFLOW: place a character on
// the picture to say where the floor is.
//
// TWO INPUTS THAT A PICTURE CANNOT SUPPLY, both the caller's:
//   floorY - the image row the fighters stand on, in pixels from the top.
//   span   - how many screens wide the picture is. 1 pins the camera and shows
//            the whole width; 2 scrolls, and fighters are twice the size.
//            See stage-geom.js for why that is one knob and not three.

const fs = require('fs');
const path = require('path');
const geom = require('./public/ikemen/stage-geom.js');

// The SFF. One sprite, group 0 number 0, which is what `spriteno = 0, 0` asks
// for. Format 12 is PNG32 - the picture goes in whole, no quantizing, no tiles.
// The engine's fmt 11/12 branch runs png.Decode and converts whatever it got to
// RGBA, so this takes ANY PNG; fmt 10 is the one that cannot (it requires
// *image.Paletted and silently drops a truecolor image).
function buildStageSff(pngBytes, w, h, axisX, axisY) {
  const PAL_OFS = 128, SPR_OFS = 144, LDATA = 172, PAL_LEN = 1024;

  const head = Buffer.alloc(LDATA);
  head.write('ElecbyteSpr\0', 0, 'latin1');
  head[12] = 0; head[13] = 0; head[14] = 0; head[15] = 2;

  // The payload opens with the PNG's own length, mirroring what a working file
  // does (see logogen.js - the engine tolerates zeros there, but "tolerated"
  // and "what ships" are different bets).
  const payload = Buffer.alloc(4 + pngBytes.length);
  payload.writeUInt32LE(pngBytes.length, 0);
  pngBytes.copy(payload, 4);

  const llen = PAL_LEN + payload.length;
  head.writeUInt32LE(SPR_OFS, 0x24);
  head.writeUInt32LE(1, 0x28);
  head.writeUInt32LE(PAL_OFS, 0x2C);
  head.writeUInt32LE(1, 0x30);
  head.writeUInt32LE(LDATA, 0x34);
  head.writeUInt32LE(llen, 0x38);
  head.writeUInt32LE(LDATA + llen, 0x3C);

  head.writeUInt16LE(1, PAL_OFS + 0);
  head.writeUInt16LE(1, PAL_OFS + 2);
  head.writeUInt16LE(256, PAL_OFS + 4);
  head.writeUInt16LE(0, PAL_OFS + 6);
  head.writeUInt32LE(0, PAL_OFS + 8);
  head.writeUInt32LE(PAL_LEN, PAL_OFS + 12);

  const n = SPR_OFS;
  head.writeUInt16LE(0, n + 0);                 // group  - spriteno = 0, 0
  head.writeUInt16LE(0, n + 2);                 // number
  head.writeUInt16LE(w, n + 4);
  head.writeUInt16LE(h, n + 6);
  head.writeInt16LE(axisX, n + 8);
  head.writeInt16LE(axisY, n + 10);
  head.writeUInt16LE(0, n + 12);                // not a link
  head[n + 14] = 12;                            // fmt 12 = PNG32
  head[n + 15] = 32;                            // coldepth
  head.writeUInt32LE(PAL_LEN, n + 16);
  head.writeUInt32LE(payload.length, n + 20);
  head.writeUInt16LE(0, n + 24);
  head.writeUInt16LE(0, n + 26);

  return Buffer.concat([head, Buffer.alloc(PAL_LEN), payload]);
}

const esc = (s) => String(s == null ? '' : s).replace(/["\r\n]/g, '').trim();

function buildStageDef(sffName, g, opts = {}) {
  const name = esc(opts.name) || 'Stage';
  const author = esc(opts.author) || '';
  const display = esc(opts.displayName) || name;
  const music = esc(opts.music);
  const r = (v) => Math.round(v);
  // Any room to move vertically? Then let the camera follow a jump, the way a
  // stock stage does; with none, the value is inert either way.
  const canRise = g.boundHigh < 0 || g.boundLow > 0;
  const scrolls = g.span > 1.001;

  return [
    '; Generated by Energy\'s Mugen Studio from a single image.',
    '; The picture is sprite 0,0 in ' + sffName + '. Its top edge is the sprite',
    '; axis, so image row N sits at stage y (N + start.y). Everything below is',
    '; derived from the image\'s size, the ground you placed, and the span you',
    '; chose (' + g.span.toFixed(2) + ' screens wide).',
    '',
    '[Info]',
    'name = "' + name + '"',
    'displayname = "' + display + '"',
    'mugenversion = 1.1',
    'author = "' + author + '"',
    '',
    '[Camera]',
    'startx = 0',
    'starty = 0',
    // How far the camera may travel. At span 1 every bound is 0 and the camera
    // is pinned - the picture IS the whole view. Wider than that and it may
    // roam exactly the part of the picture that is off screen, no further.
    'boundleft = ' + g.boundLeft,
    'boundright = ' + g.boundRight,
    'boundhigh = ' + g.boundHigh,
    'boundlow = ' + g.boundLow,
    'verticalfollow = ' + (canRise ? '.2' : '0'),
    'floortension = 0',
    'tension = ' + r(50 * g.scale),
    // The camera may pull back to reveal the whole width when the fighters
    // spread out, but never so far that the view outgrows the picture. At span
    // 1 this is 1: nothing to reveal, so no zoom.
    'startzoom = 1',
    'zoomin = 1',
    'zoomout = ' + g.zoomOut,
    // The engine clamps camera y to [boundhigh, boundlow] at ANY zoom, so
    // boundhigh above is the limit at full zoom-out; this lets the camera
    // rise further at tighter zooms by exactly the amount that keeps the
    // view's top on the same picture row (camera.go:599-602).
    'boundhighzoomdelta = ' + g.boundHighZoomDelta,
    // localcoord's height is rounded UP, so the stage reads at least as tall
    // as the screen; these let the engine cut the surplus rows from the
    // bottom, off screen anyway, instead of shifting the picture down
    // (camera.go:131-146).
    'cuthigh = ' + g.cutHigh,
    'cutlow = ' + g.cutLow,
    '',
    '[PlayerInfo]',
    'p1startx = ' + (-r(70 * g.scale)),
    'p1starty = 0',
    'p1facing = 1',
    'p2startx = ' + r(70 * g.scale),
    'p2starty = 0',
    'p2facing = -1',
    'leftbound  = ' + (-r(1000 * g.scale)),
    'rightbound = ' + r(1000 * g.scale),
    '',
    '[Bound]',
    'screenleft = ' + r(15 * g.scale),
    'screenright = ' + r(15 * g.scale),
    '',
    '[StageInfo]',
    'zoffset = ' + g.zoffset,
    'autoturn = 1',
    'resetBG = 1',
    // One screen's worth of picture. The engine fits this to the screen by
    // WIDTH (stage.go:1573), so the height here is the game's aspect applied
    // to that width, not the image's - rounded up, see cutlow above.
    'localcoord = ' + g.localcoord[0] + ', ' + g.localcoord[1],
    'xscale = 1',
    'yscale = 1',
    '',
    '[Shadow]',
    'intensity = 96',
    'color = 0,0,0',
    'yscale = .3',
    'fade.range = 0,0',
    '',
    '[Reflection]',
    'reflect = 0',
    '',
  ].concat(music ? ['[Music]', 'bgmusic = ' + music, ''] : []).concat([
    '[BGdef]',
    'spr = ' + sffName,
    'debugbg = 0',
    '',
    '[BG 0]',
    'type  = normal',
    'spriteno = 0, 0',
    'layerno = 0',
    // start.y lifts the picture so the row you placed the ground on lands at
    // zoffset; it is 0 only when the floor already sits where a stock stage
    // would put it.
    'start = ' + g.startX + ', ' + g.startY,
    'delta = 1, 1',
    'trans = none',
    'mask  = 0',
    ...(scrolls ? [] : []),
    '',
  ]).join('\n');
}

// PNG dimensions from IHDR, which is always the first chunk.
function readPngSize(buf) {
  if (buf.length < 24 || buf.readUInt32BE(0) !== 0x89504e47) {
    throw new Error('not a PNG (a stage image must be a .png)');
  }
  if (buf.toString('latin1', 12, 16) !== 'IHDR') throw new Error('PNG has no IHDR');
  return { w: buf.readUInt32BE(16), h: buf.readUInt32BE(20) };
}

// A file name the engine and the roster can both carry: stages sit FLAT in one
// directory, so two stages may not collide on a basename.
function safeName(s) {
  const base = String(s || 'stage').replace(/\.[a-z0-9]+$/i, '')
    .replace(/[^A-Za-z0-9 _-]+/g, '').replace(/\s+/g, ' ').trim();
  return base || 'stage';
}

// makeStage(imagePath, destDir, opts) -> what was written.
//   opts.floorY  image row of the ground (pixels from the top)
//   opts.span    screens wide, 1..8; clamped up to whatever keeps a screen's
//                height inside the picture
//   opts.aspect  the game's height/width; see stage-geom.gameAspect
function makeStage(srcImagePath, destDir, opts = {}) {
  const png = fs.readFileSync(srcImagePath);
  const { w, h } = readPngSize(png);
  if (!w || !h) throw new Error('that PNG reports a zero size');
  if (w > 4096 || h > 4096) {
    const size = w + 'x' + h;
    throw new Error('that image is ' + size + '; stages above 4096 on a side '
      + 'are refused because the engine has to hold every pixel in video memory');
  }
  const floorY = Number.isFinite(opts.floorY) ? opts.floorY : Math.round(h * (200 / 240));
  const g = geom.geometry(w, h, floorY, { span: opts.span, aspect: opts.aspect });

  const stem = safeName(opts.fileName || opts.name || path.basename(srcImagePath));
  const sffName = stem + '.sff';
  const defName = stem + '.def';

  fs.mkdirSync(destDir, { recursive: true });
  fs.writeFileSync(path.join(destDir, sffName),
    buildStageSff(png, w, h, g.axisX, g.axisY));
  fs.writeFileSync(path.join(destDir, defName),
    buildStageDef(sffName, g, opts), 'latin1');

  return { def: defName, sff: sffName, files: [defName, sffName], w, h,
    zoffset: g.zoffset, floorY: g.floorY, span: g.span, localcoord: g.localcoord,
    bounds: [g.boundLeft, g.boundRight, g.boundHigh, g.boundLow], zoomOut: g.zoomOut };
}

module.exports = {
  makeStage, buildStageSff, buildStageDef, readPngSize, safeName,
  geometry: geom.geometry, minSpan: geom.minSpan, gameAspect: geom.gameAspect,
};
